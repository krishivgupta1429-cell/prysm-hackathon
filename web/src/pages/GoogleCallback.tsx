import { useEffect, useState } from 'react'
import { useNavigate, useSearchParams } from 'react-router-dom'
import { setToken, setRefreshToken, fetchUser } from '@/lib/auth'
import { apiUrl } from '@/lib/api'

export default function GoogleCallback() {
  const [error, setError] = useState('')
  const [searchParams] = useSearchParams()
  const navigate = useNavigate()

  useEffect(() => {
    const code = searchParams.get('code')
    const state = searchParams.get('state')
    if (!code) {
      setError('No authorization code received from Google')
      return
    }

    async function exchangeCode() {
      try {
        const res = await fetch(apiUrl('/auth/google/callback'), {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ code, state }),
        })
        const data = await res.json()

        if (!res.ok) throw new Error(data.detail || 'Google sign-in failed')

        setToken(data.access_token)
        if (data.refresh_token) setRefreshToken(data.refresh_token)
        const user = await fetchUser()
        const isAutoGenerated = user && user.email && user.username === user.email.split('@')[0].toLowerCase().replace(/\./g, '_').slice(0, 20)
        const destination = (isAutoGenerated || data.is_new) ? '/onboarding' : '/dashboard'

        // If opened in a new tab by the login page, notify opener and close this tab
        if (window.opener && !window.opener.closed) {
          window.opener.postMessage({ type: 'google_auth_success', destination }, window.location.origin)
          window.close()
        } else {
          navigate(destination)
        }
      } catch (err: any) {
        setError(err.message || 'Google sign-in failed')
      }
    }

    exchangeCode()
  }, [searchParams])

  if (error) {
    return (
      <div className="min-h-screen bg-background flex items-center justify-center px-6">
        <div className="text-center max-w-sm">
          <p className="text-red-500 text-sm font-body mb-4">{error}</p>
          <a href="/login" className="text-sm text-foreground/50 underline hover:text-foreground/70 font-body">
            Back to login
          </a>
        </div>
      </div>
    )
  }

  return (
    <div className="min-h-screen bg-background flex items-center justify-center">
      <div className="flex flex-col items-center gap-3">
        <div className="w-8 h-8 border-2 border-foreground/10 border-t-foreground/40 rounded-full animate-spin" />
        <p className="text-foreground/30 font-body text-sm">Signing you in with Google...</p>
      </div>
    </div>
  )
}
