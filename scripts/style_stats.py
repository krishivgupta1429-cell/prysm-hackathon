"""Built during the Meta Global AI Developer Hackathon (new work).

Reads saved share results (JSON, from samples/style_refs, git-ignored) and writes aggregate style numbers to
docs/style-stats.md. Only counts and averages are written; no result text is copied.

usage: python scripts/style_stats.py [refs_dir] [out_md]
"""
import glob
import json
import re
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REFS = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "samples" / "style_refs"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "docs" / "style-stats.md"

SCORED = {"Hook & Opening", "Retention & Pacing", "Shareability", "Audio & Music", "Trend Alignment",
          "Visual Quality & Originality"}
STEP_RE = re.compile(r"Step\s*\d+\s*[—:\-–]")
TS_RE = re.compile(r"\b\d+(?:\.\d+)?\s*s\b|\b\d+:\d{2}\b")
QUOTE_RE = re.compile(r"(?<![A-Za-z])['‘\"“]([^'’\"”]{3,160})['’\"”]")
FALLBACK_RE = re.compile(r"\b(if (?:that|this|it|you|not|yes|no|the)\b|otherwise|alternatively|if you can't|if you cannot|instead,|or, if)", re.I)
READY_RE = re.compile(r"(something like|reads?|say(?:ing)?|text(?: that)? (?:says|reads)|caption|type|write|title(?:d)?|line)[^.]{0,40}['‘\"“][^'’\"”]{3,160}['’\"”]", re.I)
SAY_RE = re.compile(r"['‘\"“][^'’\"”]{3,160}['’\"”]")


def words(s):
    return len((s or "").split())


def steps(s):
    return len(STEP_RE.findall(s or ""))


def avg(xs):
    xs = [x for x in xs if x is not None]
    return round(st.mean(xs), 1) if xs else 0


def analyse(d):
    rows = []
    for p in d["parameters"]:
        how = p.get("howToDoIt") or ""
        text_all = " ".join(str(p.get(k) or "") for k in ("problem", "fix", "whatIsHappening", "whyItMatters",
                                                          "whatToChange", "howToDoIt", "whatToExpect"))
        rows.append({
            "name": p["name"], "scored": p["name"] in SCORED, "advisory": bool(p.get("advisory")),
            "steps": steps(how), "problem_w": words(p.get("problem")), "happening_w": words(p.get("whatIsHappening")),
            "why_w": words(p.get("whyItMatters")), "fix_w": words(p.get("fix")), "change_w": words(p.get("whatToChange")),
            "expect_w": words(p.get("whatToExpect")), "how_w": words(how),
            "ts_problem": len(TS_RE.findall(p.get("problem") or "")), "ts_happening": len(TS_RE.findall(p.get("whatIsHappening") or "")),
            "ts_how": len(TS_RE.findall(how)),
            "quotes_total": len(QUOTE_RE.findall(text_all)), "quotes_how": len(QUOTE_RE.findall(how)),
            "ready_how": 1 if READY_RE.search(how) or SAY_RE.search(how) else 0,
            "fallback_how": 1 if FALLBACK_RE.search(how) else 0,
            "starts_step1_dash": 1 if re.match(r"\s*Step\s*1\s*—", how) else 0,
            "emoji_in_how": 1 if re.search(r"[\U0001F300-\U0001FAFF☀-➿]", how) else 0,
        })
    return rows


def main():
    files = sorted(glob.glob(str(REFS / "ref_*.json")))
    if not files:
        sys.exit(f"no ref_*.json in {REFS}")
    per_file = []
    for f in files:
        d = json.load(open(f))
        per_file.append((d, analyse(d)))
    allrows = [r for _, rows in per_file for r in rows]
    scored = [r for r in allrows if r["scored"]]
    advis = [r for r in allrows if r["advisory"]]

    def block(rows, label):
        n = len(rows)
        return (f"| {label} | {n} | {avg([r['steps'] for r in rows])} | {min(r['steps'] for r in rows)}-{max(r['steps'] for r in rows)} | "
                f"{avg([r['problem_w'] for r in rows])} | {avg([r['happening_w'] for r in rows])} | {avg([r['why_w'] for r in rows])} | "
                f"{avg([r['change_w'] for r in rows])} | {avg([r['expect_w'] for r in rows])} | {avg([r['how_w'] for r in rows])} |")

    L = ["# Style statistics from three production results", "",
         "Built during the Meta Global AI Developer Hackathon (new work). Generated by `scripts/style_stats.py`; counts and averages only, no result text.", "",
         f"Source: {len(files)} public share results made by the original Claude pipeline (fetched read-only, saved in git-ignored `samples/style_refs/`).", "",
         "## Overall (all parameters, all results)", "",
         "| Group | Parameters | Avg steps | Steps min-max | Words in problem | Words in what-is-happening | Words in why-it-matters | Words in what-to-change | Words in what-to-expect | Words in how-to-do-it |",
         "|---|---|---|---|---|---|---|---|---|---|",
         block(allrows, "All"), block(scored, "Scored (6 per result)"), block(advis, "Advisory (4 per result)"), ""]
    L += ["## Per result", "",
          "| Result | Niche | Overall | Steps per scored param | Steps per advisory param | Words/problem | Words/why | Created |", "|---|---|---|---|---|---|---|---|"]
    for i, (d, rows) in enumerate(per_file, 1):
        sc = [r for r in rows if r["scored"]]
        ad = [r for r in rows if r["advisory"]]
        L.append(f"| ref {i} | {d.get('niche')} | {d.get('overallScore')} (after fixes {d.get('predictedScoreAfterFixes')}) | "
                 f"{[r['steps'] for r in sc]} | {[r['steps'] for r in ad]} | {avg([r['problem_w'] for r in rows])} | {avg([r['why_w'] for r in rows])} | {str(d.get('created_at'))[:10]} |")
    n_sc, n_ad = len(scored), len(advis)
    pct = lambda rows, k: f"{round(100 * sum(r[k] for r in rows) / len(rows))}%"
    L += ["", "## How quotes, timestamps, wording and fallbacks are used", "",
          "| Measure | Scored params | Advisory params |", "|---|---|---|",
          f"| Avg timestamps in problem | {avg([r['ts_problem'] for r in scored])} | {avg([r['ts_problem'] for r in advis])} |",
          f"| Avg timestamps in what-is-happening | {avg([r['ts_happening'] for r in scored])} | {avg([r['ts_happening'] for r in advis])} |",
          f"| Avg timestamps in how-to-do-it | {avg([r['ts_how'] for r in scored])} | {avg([r['ts_how'] for r in advis])} |",
          f"| Avg quoted phrases per parameter (all fields) | {avg([r['quotes_total'] for r in scored])} | {avg([r['quotes_total'] for r in advis])} |",
          f"| Avg quoted phrases inside the steps | {avg([r['quotes_how'] for r in scored])} | {avg([r['quotes_how'] for r in advis])} |",
          f"| Share with ready-to-say / ready-to-use wording in the steps | {pct(scored, 'ready_how')} | {pct(advis, 'ready_how')} |",
          f"| Share with an if/otherwise fallback in the steps | {pct(scored, 'fallback_how')} | {pct(advis, 'fallback_how')} |",
          f"| Share whose steps start with 'Step 1 —' | {pct(scored, 'starts_step1_dash')} | {pct(advis, 'starts_step1_dash')} |",
          f"| Share with an emoji inside the steps | {pct(scored, 'emoji_in_how')} | {pct(advis, 'emoji_in_how')} |", ""]
    L += ["Notes:", "",
          "- Step count is the count of `Step N —` / `Step N:` markers. The three results differ strongly (the oldest has about 3 steps everywhere; the later ones range from 2 to 9), so the guide asks for a minimum of 3 on scored parameters and allows more when the video needs it.",
          "- 'Ready-to-say wording' is a quoted phrase of text to put on screen or say (the answers give the exact words in quotes, in the creator's own register).",
          "- Weights in the production results are percentages that sum to 100 over the six scored parameters, so the production overall is the weighted average of those six (checked: the stored overall equals the 100-based weighted mean of the scores).", ""]
    # production weights check
    L += ["## Production overall = normalised weighted mean", "", "| Result | Weights sum | Weighted mean of 6 scored | Stored overall |", "|---|---|---|---|"]
    for i, (d, rows) in enumerate(per_file, 1):
        ps = [p for p in d["parameters"] if p["name"] in SCORED]
        ws = sum(p["weight"] for p in ps)
        wm = sum(p["weight"] * p["score"] for p in ps) / ws
        L.append(f"| ref {i} | {ws:g} | {wm:.1f} | {d.get('overallScore')} |")
    OUT.write_text("\n".join(L) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
